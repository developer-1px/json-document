import { expect, test } from "@playwright/test";

const html = `<style>body{font-family:Arial;color:white;background:#10243a}.slide{padding:48px;display:grid;gap:24px}h1{font-size:48px;letter-spacing:-1px;margin:0}.metric{padding:32px;border-radius:24px;background:linear-gradient(120deg,#2563eb,#14b8a6);box-shadow:0 12px 24px #0005;font-size:32px}</style><main class="slide" data-node-id="slide"><h1 data-node-id="title">분기 실적</h1><div class="metric" data-node-id="revenue">120억</div></main>`;

test("HTML source survives agent edits, human source editing, undo and reload with CSS intact", async ({ page }, info) => {
  const results: any[] = [];
  await page.route("**/api/llm-agent/tool-results/*", async route => { results.push(route.request().postDataJSON()); await route.fulfill({ body: "" }); });
  let turn = 0;
  const prompts: string[] = [];
  let holdResponse: Promise<void> | undefined;
  await page.route("**/api/llm-agent/turn", async route => {
    prompts.push(route.request().postDataJSON().messages[0].content);
    const names = route.request().postDataJSON().tools.map((t: any) => t.name);
    expect(names).toContain("create_canvas_html");
    const objectId = results.find(r => r.objectId)?.objectId;
    const calls = turn++ === 0 ? [["create_canvas_html", { html, label: "분기 실적 HTML", width: 900, height: 500 }]]
      : [["read_canvas_html", { objectId }], ["edit_canvas_html", { objectId, before: turn === 2 ? "120억" : "135억", after: turn === 2 ? "135억" : "150억" }]];
    const events = [{ type: "RUN_STARTED", threadId: "html-test", runId: `${turn}` },
      ...calls.map(([tool, args], i) => ({ type: "CUSTOM", name: "client-tool", value: { token: `${turn}-${i}`, tool, arguments: args } })),
      { type: "TEXT_MESSAGE_CONTENT", messageId: `${turn}`, delta: "반영했습니다." }, { type: "RUN_FINISHED", threadId: "html-test", runId: `${turn}` }];
    if (holdResponse) await holdResponse;
    await route.fulfill({ contentType: "text/event-stream", body: events.map(event => `data: ${JSON.stringify(event)}\n\n`).join("") });
  });
  await page.goto("/applications/canvas");
  const input = page.getByRole("textbox", { name: "Canvas 편집 요청", exact: true });
  await input.click(); await page.keyboard.insertText("HTML/CSS로 슬라이드 만들어줘"); await input.press("Enter");
  const frame = page.frameLocator("[data-canvas-html] iframe");
  await expect(frame.locator('[data-node-id="title"]')).toHaveText("분기 실적");
  expect(results[0].ok).toBe(true);
  await expect(frame.locator(".metric")).toHaveCSS("border-radius", "24px");
  await expect(frame.locator(".metric")).toHaveCSS("background-image", /linear-gradient/);
  await expect(page.locator("[data-canvas-html] iframe")).toHaveAttribute("sandbox", "allow-same-origin");
  await page.getByRole("button", { name: "전체 보기", exact: true }).click();
  await page.locator('[data-canvas-object][data-kind="embedded-document"]').dblclick();
  await frame.locator("h1").dblclick();
  await frame.locator("h1").fill("사람이 수정한 제목");
  await frame.locator("h1").press("ControlOrMeta+Enter");
  await expect(frame.locator("h1")).toHaveText("사람이 수정한 제목");
  await page.getByRole("button", { name: "실행 취소", exact: true }).click();
  await expect(frame.locator("h1")).toHaveText("분기 실적");
  await page.getByRole("button", { name: "다시 실행", exact: true }).click();
  await expect(frame.locator("h1")).toHaveText("사람이 수정한 제목");
  // Attaching a target preserves the draft and does not submit it.
  await input.click(); await page.keyboard.insertText("매출을 135억으로 변경해줘");
  await page.locator('[data-canvas-object][data-kind="embedded-document"]').press("Enter");
  await frame.locator(".metric").click();
  await page.getByRole("button", { name: "대화 1 접기", exact: true }).click();
  await page.getByRole("button", { name: "AI에게 수정 요청", exact: true }).click();
  await expect(input).toContainText("매출을 135억으로 변경해줘");
  await expect(page.getByRole("group", { name: "수정 대상", exact: true })).toContainText("120억");
  expect(prompts).toHaveLength(1);
  await input.press("Enter");
  await expect.poll(() => prompts.length).toBe(2);
  expect(prompts[1]).toContain('"nodeId":"revenue"');
  expect(prompts[1]).toContain(results[0].objectId);
  await expect(page.getByRole("group", { name: "수정 대상", exact: true })).toHaveCount(0);
  await expect(frame.locator(".metric")).toHaveText("135억");
  await expect(frame.locator("h1")).toHaveText("사람이 수정한 제목");
  expect(results.every(r => r.ok)).toBe(true);
  await page.reload();
  await expect(frame.locator(".metric")).toHaveText("135억");
  await expect(frame.locator("h1")).toHaveText("사람이 수정한 제목");
  await expect(frame.locator(".metric")).toHaveCSS("border-radius", "24px");
  // Edit inside the rendered HTML, without opening or replacing source code.
  await page.getByRole("button", { name: "전체 보기", exact: true }).click();
  await page.locator('[data-canvas-object][data-kind="embedded-document"]').dblclick();
  await frame.locator("h1").dblclick();
  await expect(frame.locator("h1")).toHaveAttribute("contenteditable", "plaintext-only");
  await frame.locator("h1").fill("화면에서 직접 수정");
  await frame.locator("h1").press("ControlOrMeta+Enter");
  await expect(frame.locator("h1")).toHaveText("화면에서 직접 수정");
  await expect(frame.locator("h1")).not.toHaveAttribute("contenteditable");
  await page.getByRole("button", { name: "실행 취소", exact: true }).click();
  await expect(frame.locator("h1")).toHaveText("사람이 수정한 제목");
  await page.getByRole("button", { name: "다시 실행", exact: true }).click();
  await expect(frame.locator("h1")).toHaveText("화면에서 직접 수정");
  await frame.locator("h1").click();
  const controls = page.locator("[data-canvas-html-controls]");
  const controlBounds = (await controls.boundingBox())!;
  const headingBounds = (await frame.locator("h1").boundingBox())!;
  expect(controlBounds.y + controlBounds.height).toBeLessThanOrEqual(headingBounds.y);
  await page.getByRole("button", { name: "확대", exact: true }).click();
  await expect.poll(async () => (await controls.boundingBox())!.height).toBeCloseTo(controlBounds.height, 0);
  await expect.poll(async () => (await controls.boundingBox())!.width).toBeCloseTo(controlBounds.width, 0);
  await page.getByRole("button", { name: "글자 크기", exact: true }).click();
  await page.getByRole("option", { name: "크게", exact: true }).click();
  await expect(frame.locator("h1")).toHaveCSS("font-size", "40px");
  await page.getByRole("button", { name: "글자색", exact: true }).click();
  await page.getByRole("option", { name: "빨강", exact: true }).click();
  await expect(frame.locator("h1")).toHaveCSS("color", "rgb(239, 68, 68)");
  // The agent changes source while native text editing is in progress. Keep the
  // draft visible, reject its stale commit, and reveal the latest source on Escape.
  await page.getByRole("button", { name: "HTML 편집 마치기", exact: true }).click();
  let release!: () => void;
  holdResponse = new Promise<void>(resolve => { release = resolve; });
  await input.click(); await page.keyboard.insertText("매출만 150억으로 변경해줘"); await input.press("Enter");
  await page.getByRole("button", { name: "전체 보기", exact: true }).click();
  await page.locator('[data-canvas-object][data-kind="embedded-document"]').dblclick();
  await frame.locator("h1").dblclick();
  await frame.locator("h1").fill("보존해야 할 입력 중 초안");
  release();
  await expect.poll(() => results.length).toBe(5);
  expect(results.every(r => r.ok)).toBe(true);
  await expect(frame.locator("h1")).toHaveText("보존해야 할 입력 중 초안");
  await frame.locator("h1").press("ControlOrMeta+Enter");
  await expect(page.getByRole("alert")).toContainText("다른 편집이 반영됐습니다");
  await expect(frame.locator("h1")).toHaveText("보존해야 할 입력 중 초안");
  await frame.locator("h1").press("Escape");
  await expect(frame.locator("h1")).toHaveText("화면에서 직접 수정");
  await expect(frame.locator(".metric")).toHaveText("150억");
  await page.reload();
  await expect(frame.locator("h1")).toHaveText("화면에서 직접 수정");
  await expect(frame.locator("h1")).toHaveCSS("font-size", "40px");
  await expect(frame.locator("h1")).toHaveCSS("color", "rgb(239, 68, 68)");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "대화 1 접기", exact: true }).click();
  await page.getByRole("button", { name: "전체 보기", exact: true }).click();
  await page.locator('[data-canvas-object][data-kind="embedded-document"]').dblclick();
  await frame.locator("h1").click();
  const narrowControls = (await controls.boundingBox())!;
  expect(narrowControls.x).toBeGreaterThanOrEqual(0);
  expect(narrowControls.x + narrowControls.width).toBeLessThanOrEqual(390);
  await page.getByRole("button", { name: "글자색", exact: true }).click();
  const palette = page.getByRole("listbox", { name: "글자색", exact: true });
  const paletteBounds = (await palette.boundingBox())!;
  expect(paletteBounds.x).toBeGreaterThanOrEqual(0);
  expect(paletteBounds.x + paletteBounds.width).toBeLessThanOrEqual(390);
  await palette.press("Escape");
  await page.screenshot({ path: info.outputPath("html-canvas.png") });
});

test("native selection attaches to chat, can be removed, and stays scoped on a narrow screen", async ({ page }) => {
  await page.goto("/applications/canvas");
  await page.getByRole("button", { name: "사각형", exact: true }).click();
  await page.mouse.move(200, 250); await page.mouse.down(); await page.mouse.move(480, 420); await page.mouse.up();
  await page.getByRole("button", { name: "선택", exact: true }).click();
  const object = page.locator("[data-canvas-object]");
  await object.click();
  await page.getByRole("button", { name: "AI에게 수정 요청", exact: true }).click();
  const input = page.getByRole("textbox", { name: "Canvas 편집 요청", exact: true });
  await expect(input).toBeFocused();
  await input.click(); await page.keyboard.insertText("작성 중인 요청");
  await page.getByRole("button", { name: "대상 해제", exact: true }).click();
  await expect(page.getByRole("group", { name: "수정 대상", exact: true })).toHaveCount(0);
  await expect(input).toContainText("작성 중인 요청");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "대화 1 접기", exact: true }).click();
  await page.getByRole("button", { name: "전체 보기", exact: true }).click();
  await object.click();
  await page.getByRole("button", { name: "AI에게 수정 요청", exact: true }).click();
  await expect(input).toBeFocused();
  await expect(input).toContainText("작성 중인 요청");
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390);
});
